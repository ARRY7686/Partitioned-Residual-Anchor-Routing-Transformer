"""Collects the results of experiments 03, 06 and 07 into one Markdown summary with means,
standard deviations and paired 95% t-intervals over seeds 42/43/44.

    python summarize_results.py            # writes RESULTS_SUMMARY.md next to this file
"""
import glob
import json
import os
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
SEEDS = (42, 43, 44)
T95 = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776}   # two-sided t quantiles by n
out = []


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def runs(folder, prefix, field="final_test_acc"):
    """{seed: score} for result files <prefix>_seed<s>.json."""
    scores = {}
    for seed in SEEDS:
        path = os.path.join(folder, f"{prefix}_seed{seed}.json")
        if os.path.exists(path):
            scores[seed] = load(path)[field]
    return scores


def collapse_runs(folder, kind):
    scores = {}
    for path in glob.glob(os.path.join(folder, "step0_results_A16_seed*.json")):
        data = load(path)
        if kind in data:
            r = data[kind]
            blocks = r["metrics_trained"]
            scores[r["seed"]] = (r["history"][-1]["test_acc"],
                                 st.mean(b["map_similarity"] for b in blocks),
                                 st.mean(b["anchor_spread"] for b in blocks))
    return scores


def mean_std(values):
    values = list(values)
    return f"{st.mean(values):.2f} ± {st.stdev(values):.2f}" if len(values) > 1 else f"{values[0]:.2f}"


def paired(a, b):
    seeds = sorted(set(a) & set(b))
    diffs = [a[s] - b[s] for s in seeds]
    m = st.mean(diffs)
    if len(diffs) < 2:
        return f"{m:+.2f} (n=1)"
    h = T95[len(diffs)] * st.stdev(diffs) / len(diffs) ** 0.5
    return f"{m:+.2f} [{m - h:+.2f}, {m + h:+.2f}] (n={len(diffs)})"


def table(title, rows, header):
    out.append(f"\n### {title}\n")
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")


# ---------------------------------------------------------------- Experiment 03
e03 = os.path.join(HERE, "03_anchor_collapse", "results")
original = {"partition": {42: 45.68, 43: 46.48, 44: 46.77}, "anchorformer": {42: 42.34, 43: 43.28, 44: 41.95}}
c = {"partition": {s: (v, 0.0, 0.60) for s, v in original["partition"].items()},
     "partition_local": collapse_runs(os.path.join(e03, "ablation_local"), "partition_local"),
     "rpattention": collapse_runs(os.path.join(e03, "rpattention"), "rpattention"),
     "rpattention_nolocal": collapse_runs(os.path.join(e03, "ablation_local"), "rpattention_nolocal")}
acc = {k: {s: v[0] for s, v in d.items()} for k, d in c.items()}
out.append("# Results summary (generated by summarize_results.py)")
table("Exp 03: collapse benchmark, CIFAR-100 224², 16 anchors, 10 epochs",
      [(k, mean_std(acc[k].values()), f"{st.mean(v[1] for v in c[k].values()):.3f}",
        f"{st.mean(v[2] for v in c[k].values()):.3f}") for k in c],
      ["pathway", "test acc", "map similarity", "spread"])
table("Exp 03: paired gaps", [
    ("partition + conv − RPAttention (both with conv)", paired(acc["partition_local"], acc["rpattention"])),
    ("partition − RPAttention (both without conv)", paired(acc["partition"], acc["rpattention_nolocal"])),
    ("conv effect on partition", paired(acc["partition_local"], acc["partition"])),
    ("conv effect on RPAttention", paired(acc["rpattention"], acc["rpattention_nolocal"])),
    ("RPAttention (with conv) − partition (without)", paired(acc["rpattention"], acc["partition"])),
], ["comparison", "mean [95% CI]"])

# ---------------------------------------------------------------- Experiment 06
e06 = os.path.join(HERE, "06_main_comparison", "results", "exp06_results")
b = {k: runs(e06, f"B_{k}") for k in ("focus_A16", "fixed_A16", "densewin", "vit256")}
t = {k: runs(e06, f"T_{k}") for k in ("focus_A16", "fixed_A16", "densewin", "vit256")}
table("Exp 06: dense with local windows (densewin)", [
    ("Cluttered CIFAR-10, 30 ep", *(mean_std(b[k].values()) for k in b)),
    ("Tiny ImageNet canvas, 15 ep", *(mean_std(t[k].values()) for k in t)),
], ["task", "focus-16", "fixed-16", "densewin", "ViT 256²"])
table("Exp 06: paired gaps against densewin", [
    ("Cluttered: focus − densewin", paired(b["focus_A16"], b["densewin"])),
    ("Cluttered: fixed − densewin", paired(b["fixed_A16"], b["densewin"])),
    ("Cluttered: densewin − ViT 256²", paired(b["densewin"], b["vit256"])),
    ("Tiny IN: focus − densewin", paired(t["focus_A16"], t["densewin"])),
    ("Tiny IN: fixed − densewin", paired(t["fixed_A16"], t["densewin"])),
], ["comparison", "mean [95% CI]"])
ref = runs(e06, "D2_full_clip")
w = {k: runs(e06, f"W_{k}_clip") for k in ("scatter2", "scatter3", "gumbel")}
table("Exp 06 phase W (focus-16, Cluttered, 10 ep, clip + warmup)",
      [("reference (own anchor, hard)", mean_std(ref.values()), "")] +
      [(k, mean_std(v.values()), paired(v, ref)) for k, v in w.items()],
      ["variant", "test acc", "− reference"])

# ---------------------------------------------------------------- Experiment 07
e07 = os.path.join(HERE, "07_high_resolution", "results", "exp07_results")
f = "final_test_score"
n_models = ("resnet18_lr1e-3", "pvt", "vit256", "fixed_A64", "densewin", "focus_A64", "vit128", "vit_native")
n = {k: runs(e07, f"N_{k}", f) for k in n_models}
n["focus_A64"].pop(42, None)   # the seed-42 run at lr 2e-4 diverged; reported separately
table("Exp 07: Megapixel MNIST 512², 30 epochs (focus: stable seeds 43, 44)",
      [(k, mean_std(v.values()), dict(sorted((s, round(x, 1)) for s, x in v.items()))) for k, v in n.items()],
      ["model", "test acc", "per seed"])
table("Exp 07: Megapixel MNIST paired gaps", [
    ("fixed − densewin", paired(n["fixed_A64"], n["densewin"])),
    ("fixed − ViT native 512²", paired(n["fixed_A64"], n["vit_native"])),
    ("densewin − ViT native 512²", paired(n["densewin"], n["vit_native"])),
    ("ViT 256² − fixed", paired(n["vit256"], n["fixed_A64"])),
    ("fixed − ViT 128²", paired(n["fixed_A64"], n["vit128"])),
    ("focus − fixed (seeds 43, 44)", paired(n["focus_A64"], n["fixed_A64"])),
], ["comparison", "mean [95% CI]"])
fix = {name: load(os.path.join(e07, f"N_focus_{name}_seed42.json"))[f]
       for name in ("A64", "A64_lr1e-4", "A16") if os.path.exists(os.path.join(e07, f"N_focus_{name}_seed42.json"))}
table("Exp 07: focus seed 42 instability (Megapixel MNIST, 30 epochs)",
      [(k, round(v, 2)) for k, v in fix.items()], ["setting", "test acc"])
dm_models = ("resnet18_lr1e-3", "focus_A64", "densewin", "fixed_A64", "vit_native", "pvt", "vit480")
dm = {k: runs(e07, f"DM_{k}", f) for k in dm_models}
gflops = {k: load(os.path.join(e07, f"DM_{k}_seed43.json"))["gflops_total"] for k in dm_models}
table("Exp 07: DFG traffic signs, full HD, max-pooled heads, 20 epochs (test mAP)",
      [(k, mean_std(v.values()), f"{gflops[k]:.0f}") for k, v in dm.items()], ["model", "test mAP", "GFLOPs"])
table("Exp 07: DFG paired gaps", [
    ("focus − fixed", paired(dm["focus_A64"], dm["fixed_A64"])),
    ("focus − densewin", paired(dm["focus_A64"], dm["densewin"])),
    ("fixed − densewin", paired(dm["fixed_A64"], dm["densewin"])),
    ("fixed − ViT native", paired(dm["fixed_A64"], dm["vit_native"])),
    ("ViT native − ViT 480-wide", paired(dm["vit_native"], dm["vit480"])),
    ("fixed − ViT 480-wide", paired(dm["fixed_A64"], dm["vit480"])),
    ("ResNet-18 − focus", paired(dm["resnet18_lr1e-3"], dm["focus_A64"])),
], ["comparison", "mean [95% CI]"])
avg = {k: runs(e07, f"D_{k}", f) for k in ("focus_A64", "fixed_A64", "densewin", "vit_native", "vit480", "resnet18_lr1e-3")}
table("Exp 07: DFG with average pooling (seed 42 probes)",
      [(k, round(v[42], 2) if 42 in v else "") for k, v in avg.items()], ["model", "test mAP"])

rows = []
for path in sorted(glob.glob(os.path.join(e07, "C_*.json"))):
    r = load(path)
    name = os.path.basename(path)[2:-5]
    step = "OOM" if r.get("train_oom") else f"{r.get('train_step_ms', float('nan')):.1f}"
    mem = r.get("peak_train_memory_mb")
    rows.append((name, f"{r.get('gflops_total') or float('nan'):.1f}", step,
                 "" if mem is None else f"{mem / 1024:.1f}", f"{r.get('throughput_img_s') or float('nan'):.1f}"))
table("Exp 07: cost sweep (A100, bf16, untrained)", rows,
      ["config", "GFLOPs", "train ms/step", "train GB", "inference img/s"])

with open(os.path.join(HERE, "RESULTS_SUMMARY.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print("\n".join(out))
